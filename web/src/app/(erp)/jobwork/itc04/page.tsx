"use client";

import * as React from "react";
import Link from "next/link";
import { Download, FileSpreadsheet, Info } from "lucide-react";
import { toast } from "sonner";
import { Breadcrumbs } from "@/components/erp/control-panel";
import { Banner, Card } from "@/components/erp/form-view";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Select } from "@/components/ui/form";
import { useItemName } from "@/components/inventory/shared";
import { company, partyById } from "@/lib/data/masters";
import { useRole } from "@/lib/store/app";
import { useInventory } from "@/lib/store/inventory";
import { type Challan, pendingQty, useJobwork } from "@/lib/store/jobwork";
import { formatDate, formatINR, formatNum } from "@/lib/utils";

const PERIODS = [
  { key: "2026-H1", label: "Apr-Sep 2026 (FY 2026-27, H1)", from: "2026-04-01", to: "2026-09-30", due: "25-Oct-2026" },
  { key: "2025-H2", label: "Oct 2025-Mar 2026 (FY 2025-26, H2)", from: "2025-10-01", to: "2026-03-31", due: "25-Apr-2026" },
  { key: "2025-H1", label: "Apr-Sep 2025 (FY 2025-26, H1)", from: "2025-04-01", to: "2025-09-30", due: "25-Oct-2025" },
];

const inRange = (d: string, from: string, to: string) => d >= from && d <= to;

export default function Itc04Page() {
  const role = useRole();
  const challans = useJobwork((s) => s.challans);
  const items = useInventory((s) => s.items);
  const name = useItemName();
  const [period, setPeriod] = React.useState("2026-H1");
  const p = PERIODS.find((x) => x.key === period)!;
  const it = (id: string) => items.find((i) => i.id === id)!;
  const issued = challans.filter((c) => c.status !== "draft");

  const sent = issued.filter((c) => inRange(c.date, p.from, p.to)).flatMap((c) => c.lines.map((l) => ({ c, l })));
  const received = issued.flatMap((c) =>
    c.receipts.filter((r) => inRange(r.date, p.from, p.to)).flatMap((r) => r.lines.map((rl) => ({ c, r, rl, l: c.lines.find((x) => x.id === rl.lineId)! }))),
  );
  // Pending at period end: sent on or before period end, less receipts up to period end.
  const pending = issued
    .filter((c) => c.date <= p.to)
    .flatMap((c) =>
      c.lines.map((l) => {
        const back = c.receipts.filter((r) => r.date <= p.to).flatMap((r) => r.lines.filter((x) => x.lineId === l.id));
        const qty = l.qty - back.reduce((a, x) => a + x.returned + x.loss, 0);
        return { c, l, qty };
      }),
    )
    .filter((x) => x.qty > 0);
  const losses = received.filter((x) => x.rl.loss > 0);

  const goodsLabel = (c: Challan, l: Challan["lines"][number]) => l.description ?? name(l.itemId);
  const hsn = (c: Challan, l: Challan["lines"][number]) => (l.description ? "8207" : it(l.itemId).hsn);

  const exportCsv = () => {
    const rows = [
      ["Table", "Challan no", "Challan date", "Job-worker GSTIN", "State", "Description", "HSN", "UQC", "Quantity", "Taxable value", "Goods type", "Receipt no", "Receipt date", "Losses"],
      ...sent.map(({ c, l }) => ["4 - Sent", c.number, c.date, partyById(c.jobWorkerId).gstin, partyById(c.jobWorkerId).state, goodsLabel(c, l), hsn(c, l), l.uom.toUpperCase(), l.qty, (l.qty * l.valuePerUnit).toFixed(2), c.goodsClass === "capital" ? "Capital goods" : "Inputs", "", "", ""]),
      ...received.map(({ c, r, rl, l }) => ["5A - Received back", c.number, c.date, partyById(c.jobWorkerId).gstin, partyById(c.jobWorkerId).state, goodsLabel(c, l), hsn(c, l), l.uom.toUpperCase(), rl.returned, "", c.goodsClass === "capital" ? "Capital goods" : "Inputs", r.number, r.date, rl.loss]),
    ];
    const blob = new Blob([rows.map((r) => r.map((v) => JSON.stringify(v)).join(",")).join("\n")], { type: "text/csv" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = `ITC-04_${company.gstin}_${period}.csv`;
    a.click();
    toast.success("ITC-04 data exported", { description: `${sent.length + received.length} rows · ${p.label}` });
  };

  const th = "px-3 py-2 text-left text-xs font-semibold text-ink-2";
  const td = "px-3 py-2";

  return (
    <div className="flex flex-col">
      <div className="flex flex-wrap items-center gap-3 border-b border-line bg-surface px-4 py-2.5 sm:px-6">
        <Breadcrumbs items={[{ label: "Job-work", href: "/jobwork/challans" }, { label: "ITC-04 report" }]} />
        <div className="ml-auto flex flex-wrap items-center gap-2">
          <Select aria-label="Return period" value={period} onChange={(e) => setPeriod(e.target.value)} className="w-72">
            {PERIODS.map((x) => <option key={x.key} value={x.key}>{x.label}</option>)}
          </Select>
          <Button onClick={exportCsv}><Download /> Export CSV</Button>
          <Button variant="primary" onClick={() => { exportCsv(); toast("Excel workbook in GST offline-tool layout is generated by the reporting service (R1 export job)"); }}><FileSpreadsheet /> Excel for offline tool</Button>
        </div>
      </div>
      <Banner tone="info" icon={<Info />}>
        Data for filing only — verify with your CA before upload. Frequency: <b>half-yearly</b> because aggregate turnover is above ₹5 crore ({company.turnoverBand}); annual otherwise (PRD §12). Due date for this period: {p.due} [verify].
      </Banner>

      <div className="mx-auto w-full max-w-[1400px] space-y-4 p-3 sm:p-5">
        <section className="grid grid-cols-2 overflow-hidden rounded-xl border border-line bg-surface shadow-xs md:grid-cols-4" aria-label="Summary">
          {[
            ["Challans sent", new Set(sent.map((x) => x.c.id)).size, `${formatNum(sent.reduce((a, x) => a + x.l.qty, 0))} units`],
            ["Received back", received.length, `${formatNum(received.reduce((a, x) => a + x.rl.returned, 0))} units`],
            ["Pending at period end", pending.length, `${formatNum(pending.reduce((a, x) => a + x.qty, 0))} units`],
            ["Losses declared", losses.length, `${formatNum(losses.reduce((a, x) => a + x.rl.loss, 0))} units`],
          ].map(([l, v, s]) => (
            <div key={l as string} className="border-r border-b border-line p-4 last:border-r-0 md:border-b-0">
              <div className="text-xs font-medium text-ink-3">{l}</div>
              <div className="tabular mt-1 text-xl font-semibold">{v}</div>
              <div className="text-xs text-ink-3">{s}</div>
            </div>
          ))}
        </section>

        <Card title="Table 4 · Goods sent to job-worker" action={<span className="text-xs text-ink-3">{sent.length} lines</span>} bodyClassName="p-0">
          <div className="overflow-x-auto">
            <table className="w-full min-w-[900px] text-sm">
              <thead className="bg-surface-2"><tr className="border-b border-line"><th className={th}>Challan</th><th className={th}>Date</th><th className={th}>Job-worker GSTIN</th><th className={th}>State</th><th className={th}>Description</th><th className={th}>HSN</th><th className={`${th} text-right`}>Qty</th>{role.seesCost && <th className={`${th} text-right`}>Taxable value</th>}<th className={th}>Type</th></tr></thead>
              <tbody>
                {sent.map(({ c, l }) => (
                  <tr key={c.id + l.id} className="border-b border-line last:border-0">
                    <td className={td}><Link href={`/jobwork/challans/${c.id}`} className="font-mono text-xs font-medium text-primary-700 hover:underline">{c.number}</Link></td>
                    <td className={td}>{formatDate(c.date)}</td>
                    <td className={`${td} font-mono text-xs`}>{partyById(c.jobWorkerId).gstin}</td>
                    <td className={td}>{partyById(c.jobWorkerId).state}</td>
                    <td className={td}>{goodsLabel(c, l)}</td>
                    <td className={`${td} font-mono text-xs`}>{hsn(c, l)}</td>
                    <td className={`${td} tabular text-right`}>{formatNum(l.qty)} {l.uom}</td>
                    {role.seesCost && <td className={`${td} tabular text-right`}>{formatINR(l.qty * l.valuePerUnit)}</td>}
                    <td className={td}>{c.goodsClass === "capital" ? <Badge tone="progress" dot={false}>Capital</Badge> : <Badge tone="neutral" dot={false}>Inputs</Badge>}</td>
                  </tr>
                ))}
                {!sent.length && <tr><td colSpan={9} className="px-3 py-8 text-center text-ink-3">No goods sent in this period</td></tr>}
              </tbody>
            </table>
          </div>
        </Card>

        <Card title="Table 5A · Goods received back from job-worker" action={<span className="text-xs text-ink-3">{received.length} lines</span>} bodyClassName="p-0">
          <div className="overflow-x-auto">
            <table className="w-full min-w-[860px] text-sm">
              <thead className="bg-surface-2"><tr className="border-b border-line"><th className={th}>Original challan</th><th className={th}>Sent on</th><th className={th}>Job-worker</th><th className={th}>Receipt</th><th className={th}>Received on</th><th className={th}>Description</th><th className={`${th} text-right`}>Qty back</th><th className={`${th} text-right`}>Loss</th></tr></thead>
              <tbody>
                {received.map(({ c, r, rl, l }) => (
                  <tr key={c.id + r.id + rl.lineId} className="border-b border-line last:border-0">
                    <td className={`${td} font-mono text-xs`}>{c.number}</td>
                    <td className={td}>{formatDate(c.date)}</td>
                    <td className={td}>{partyById(c.jobWorkerId).name}</td>
                    <td className={`${td} font-mono text-xs`}>{r.number}</td>
                    <td className={td}>{formatDate(r.date)}</td>
                    <td className={td}>{goodsLabel(c, l)}</td>
                    <td className={`${td} tabular text-right`}>{formatNum(rl.returned)}</td>
                    <td className={`${td} tabular text-right ${rl.loss ? "text-warning" : "text-ink-3"}`}>{formatNum(rl.loss)}</td>
                  </tr>
                ))}
                {!received.length && <tr><td colSpan={8} className="px-3 py-8 text-center text-ink-3">Nothing received back in this period</td></tr>}
              </tbody>
            </table>
          </div>
        </Card>

        <div className="grid gap-4 lg:grid-cols-2">
          <Card title="Goods pending with job-workers at period end" bodyClassName="p-0">
            <table className="w-full text-sm">
              <thead className="bg-surface-2"><tr className="border-b border-line"><th className={th}>Challan</th><th className={th}>Job-worker</th><th className={th}>Goods</th><th className={`${th} text-right`}>Pending</th></tr></thead>
              <tbody>
                {pending.map(({ c, l, qty }) => (
                  <tr key={c.id + l.id} className="border-b border-line last:border-0">
                    <td className={`${td} font-mono text-xs`}>{c.number}</td>
                    <td className={td}>{partyById(c.jobWorkerId).name}</td>
                    <td className={td}>{goodsLabel(c, l)}</td>
                    <td className={`${td} tabular text-right font-semibold`}>{formatNum(qty)} {l.uom}</td>
                  </tr>
                ))}
                {!pending.length && <tr><td colSpan={4} className="px-3 py-8 text-center text-ink-3">Nothing pending</td></tr>}
              </tbody>
            </table>
          </Card>
          <Card title="Losses and wastage" bodyClassName="p-0">
            <table className="w-full text-sm">
              <thead className="bg-surface-2"><tr className="border-b border-line"><th className={th}>Challan</th><th className={th}>Goods</th><th className={`${th} text-right`}>Loss</th><th className={`${th} text-right`}>Loss %</th></tr></thead>
              <tbody>
                {losses.map(({ c, r, rl, l }) => (
                  <tr key={c.id + r.id + rl.lineId} className="border-b border-line last:border-0">
                    <td className={`${td} font-mono text-xs`}>{c.number}</td>
                    <td className={td}>{goodsLabel(c, l)}</td>
                    <td className={`${td} tabular text-right`}>{formatNum(rl.loss)}</td>
                    <td className={`${td} tabular text-right text-ink-2`}>{((rl.loss / Math.max(1, rl.returned + rl.loss)) * 100).toFixed(2)}%</td>
                  </tr>
                ))}
                {!losses.length && <tr><td colSpan={4} className="px-3 py-8 text-center text-ink-3">No losses recorded</td></tr>}
              </tbody>
            </table>
            <p className="border-t border-line px-3 py-2 text-xs text-ink-3">Total pending now across all challans: {formatNum(issued.reduce((a, c) => a + c.lines.reduce((x, l) => x + pendingQty(l), 0), 0))} units.</p>
          </Card>
        </div>
      </div>
    </div>
  );
}
